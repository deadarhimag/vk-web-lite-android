package com.example.vkweb.messages

/**
 * Как вести себя переписке, когда пришло обновление (4.67; до этого — условия внутри MessagesActivity.showHistoryData).
 * Без зависимостей от Android: проверяется тестами. Порядок проверок важен — он и есть правило.
 */
object ChatScrollPolicy {

    enum class Action(val label: String) {
        /** Первая порция — к последнему сообщению. */
        FIRST_PAGE("первая порция — к последнему"),

        /**
         * 5.00.12: только что отправили — к последнему, где бы ни стоял список. Отчёт 12.11 09:51: при открытой
         * клавиатуре список считал, что человек не внизу, держал верхнюю строку, и своё сообщение уезжало за край.
         */
        FOLLOW_SENT("после отправки — к последнему"),

        /** Новые снизу, человек внизу — доехать до последнего (несколько штук — плавно, см. [smooth]). */
        NEW_AT_BOTTOM("новые снизу — к последнему"),

        /**
         * 4.0, «прыжки при входе и действиях»: человек внизу, а выше что-то поменяло высоту (свежая история поверх
         * сохранённой, разделители дней, статус, догрузились старые) — список держался за верхнюю строку, и низ уезжал.
         * Внизу — значит внизу: остаёмся у последнего.
         */
        STAY_AT_BOTTOM("внизу — остаёмся внизу"),

        /**
         * Сверху догрузились старые — на месте остаётся то, что человек читал. Только если они правда добавились сверху и
         * список стоит: раньше позиция «восстанавливалась» на каждое обновление, и прокрутка обрывалась (отчёт 3.59).
         */
        KEEP_ROW_AFTER_OLDER("старые сверху — строка на месте"),

        /** Читает выше, список стоит, а строка перед глазами сдвинулась (выросло что-то над ней) — вернуть её на место. */
        KEEP_ROW("строка на месте"),

        /** Человек листает — не мешать. */
        NONE("без прокрутки (листают)"),
    }

    /** Сколько новых снизу ещё доезжать плавно; больше — сразу, без долгой анимации. */
    const val SMOOTH_MAX = 5

    /**
     * [previousEmpty] — до обновления сообщений не было; [newAtEnd] — последнее сообщение сменилось; [wasAtBottom] — человек
     * был внизу; [idle] — список не листают; [anchorFound] — строка, которую читали, есть в новом списке; [prepended] —
     * сменилось первое сообщение (догрузились старые); [followSent] — недавно отправили своё, а человек не листает.
     */
    fun decide(
        previousEmpty: Boolean,
        newAtEnd: Boolean,
        wasAtBottom: Boolean,
        idle: Boolean,
        anchorFound: Boolean,
        prepended: Boolean,
        followSent: Boolean = false,
    ): Action = when {
        previousEmpty -> Action.FIRST_PAGE
        followSent && idle -> Action.FOLLOW_SENT
        newAtEnd && wasAtBottom -> Action.NEW_AT_BOTTOM
        wasAtBottom && idle -> Action.STAY_AT_BOTTOM
        anchorFound && prepended && idle -> Action.KEEP_ROW_AFTER_OLDER
        anchorFound && idle -> Action.KEEP_ROW
        else -> Action.NONE
    }

    /** Для [Action.NEW_AT_BOTTOM]: доезжать плавно — добавилось от одного до [SMOOTH_MAX]. */
    fun smooth(added: Int): Boolean = added in 1..SMOOTH_MAX
}
