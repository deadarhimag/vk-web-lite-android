package com.example.vkweb.web

import android.webkit.WebView

/**
 * Страница VK не узнаёт, что экран заблокирован, приложение свёрнуто или страница закрыта своим экраном
 * (assets/page_visibility.js): для неё окно всегда видимо и в фокусе. Иначе её скрипты на блокировке экрана
 * останавливают плеер и «засыпают» — фоновое воспроизведение и чтение сообщений обрывались бы.
 *
 * Ставится первым из скриптов начала документа (порядок установки = порядок выполнения), чтобы страница
 * не успела запомнить настоящие значения. Работает во всех окнах VK, независимо от настройки
 * «Скрывать сведения об устройстве».
 *
 * Свою работу скрипты приложения по-прежнему сверяют с настоящей видимостью (`window.__vkWebVisibility`),
 * чтобы не тратить батарею, пока окно не видно.
 */
object PageVisibility {

    const val ASSET = "page_visibility.js"

    fun install(webView: WebView) = DocumentStartScript.install(webView, ASSET, "WebView слишком старый: страница может узнать о блокировке экрана")
}
