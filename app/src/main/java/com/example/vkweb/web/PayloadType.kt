package com.example.vkweb.web

/**
 * Тип сообщения страницы без полного разбора JSON. Без зависимостей от Android: проверяется обычными тестами.
 * Скрипты страницы всегда ставят type первым полем, поэтому хватает взглянуть на начало строки; это позволяет
 * отбросить повтор или передать большое сообщение дальше, не разбирая его целиком.
 */
object PayloadType {

    private val PREFIX = Regex("^\\{\\s*\"type\"\\s*:\\s*\"([A-Za-z0-9_-]{1,32})\"")

    /** Тип из начала сообщения; пустая строка — не нашли (тогда сообщение разбирается целиком). */
    fun of(raw: String): String = PREFIX.find(raw)?.groupValues?.get(1).orEmpty()
}
