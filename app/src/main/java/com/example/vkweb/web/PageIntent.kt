package com.example.vkweb.web

import com.example.vkweb.clips.ClipPaths

/**
 * Чей это переход страницы — человека или самой страницы (4.38). Без зависимостей от Android: проверяется тестами.
 *
 * Страница VK под своими экранами живёт своей жизнью: её проигрыватель клипов, не получив файл ролика (файлы скрытой
 * страницы не грузятся, 4.22), перелистывает на следующий клип или уходит в «Тренды», лента клипов сама открывает
 * первый ролик. Отчёт 4.33: «страница сама перешла с /clip… на /clips_trends через 5 с», затем — снова на клип, и
 * приложение открывало свой проигрыватель и переключало меню, хотя человек ничего не нажимал. Отсюда «самопроизвольные
 * запуски», «перекидывание на другой интерфейс» и «Назад», гоняющее между «Клипами» и «Видео».
 *
 * Переход считается желанным, если за [WINDOW_MS] до него человек коснулся видимой страницы или приложение само
 * что-то открыло (меню, свой экран, переписка, «Назад»).
 */
object PageIntent {

    const val WINDOW_MS = 3_000L

    fun isWanted(nowMs: Long, lastIntentAtMs: Long): Boolean =
        lastIntentAtMs > 0 && nowMs >= lastIntentAtMs && nowMs - lastIntentAtMs <= WINDOW_MS

    /**
     * Страница сама ушла на клип или видео, пока на экране свой экран: экран, меню и заголовок не трогать, свой
     * проигрыватель не открывать — переход для человека невидим, страница скрыта.
     */
    fun isWander(path: String?, wanted: Boolean, screenShown: Boolean): Boolean =
        !wanted && screenShown && BackPolicy.isPlayerPage(path) && !ClipPaths.isFeed(path)
}
